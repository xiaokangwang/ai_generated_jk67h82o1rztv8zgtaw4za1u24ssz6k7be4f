TEXT ·xorBytesInplaceAsm(SB), NOSPLIT, $0-24
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVQ n+16(FP), CX

loop64_inplace:
	CMPQ CX, $64
	JB loop16_inplace
	MOVOU 0(DI), X0
	MOVOU 16(DI), X1
	MOVOU 32(DI), X2
	MOVOU 48(DI), X3
	MOVOU 0(SI), X4
	MOVOU 16(SI), X5
	MOVOU 32(SI), X6
	MOVOU 48(SI), X7
	PXOR X4, X0
	PXOR X5, X1
	PXOR X6, X2
	PXOR X7, X3
	MOVOU X0, 0(DI)
	MOVOU X1, 16(DI)
	MOVOU X2, 32(DI)
	MOVOU X3, 48(DI)
	ADDQ $64, DI
	ADDQ $64, SI
	SUBQ $64, CX
	JMP loop64_inplace

loop16_inplace:
	CMPQ CX, $16
	JB loop8_inplace
	MOVOU 0(DI), X0
	MOVOU 0(SI), X1
	PXOR X1, X0
	MOVOU X0, 0(DI)
	ADDQ $16, DI
	ADDQ $16, SI
	SUBQ $16, CX
	JMP loop16_inplace

loop8_inplace:
	CMPQ CX, $8
	JB loop1_inplace
	MOVQ 0(DI), AX
	XORQ 0(SI), AX
	MOVQ AX, 0(DI)
	ADDQ $8, DI
	ADDQ $8, SI
	SUBQ $8, CX
	JMP loop8_inplace

loop1_inplace:
	TESTQ CX, CX
	JE done_inplace
	MOVBLZX 0(DI), AX
	MOVBLZX 0(SI), BX
	XORQ BX, AX
	MOVB AL, 0(DI)
	INCQ DI
	INCQ SI
	DECQ CX
	JMP loop1_inplace

done_inplace:
	RET

